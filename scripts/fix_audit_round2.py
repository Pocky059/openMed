def apply_rule_fixes(rules):
    """B 组字段修订 + C 组新增规则。"""
    by_id = {r["id"]: r for r in rules}
    for rid, updates in RULE_UPDATES.items():
        if rid not in by_id:
            print(f"  [警告] 规则 {rid} 不存在，跳过")
            continue
        for key, val in updates.items():
            old = by_id[rid].get(key)
            if old == val:
                continue
            by_id[rid][key] = val
            print(f"  {rid}.{key}: 已更新")
    for new_rule in NEW_RULES:
        if new_rule["id"] in by_id:
            print(f"  [警告] {new_rule['id']} 已存在，跳过新增")
            continue
        rules.append(new_rule)
        print(f"  + 新增规则 {new_rule['id']}: {new_rule['drug_a']['name']}×{new_rule['drug_b']['name']} "
              f"({new_rule['severity']}/{new_rule['evidence_level']})")
    print(f"规则库：{len(RULE_UPDATES)} 条字段修订，{len(NEW_RULES)} 条新增")
    return rules


def match_entry(entry, match):
    """判断条目是否命中匹配键。"""
    if "rule_id" in match:
        return entry.get("rule_id") == match["rule_id"]
    if entry.get("title") != match.get("title"):
        return False
    if "source_contains" in match and match["source_contains"] not in entry.get("source", ""):
        return False
    return True


def apply_corpus_fixes():
    """对 corpus/ 下每个分药 jsonl 应用条目级修改（源文件，合并产物由 --merge 重建）。"""
    # 读入全部文件
    files = {}
    for f in sorted(CORPUS_DIR.glob("*.jsonl")):
        entries = [json.loads(l) for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]
        files[f] = entries

    matched_updates = 0
    dirty = set()
    for i, upd in enumerate(CORPUS_UPDATES):
        hits = []
        for f, entries in files.items():
            for e in entries:
                if match_entry(e, upd["match"]):
                    hits.append((f, e))
        if len(hits) == 0:
            print(f"  [错误] 第 {i} 条修改未匹配到任何条目: {upd['match']}")
            sys.exit(1)
        if len(hits) > 1:
            print(f"  [错误] 第 {i} 条修改匹配到 {len(hits)} 个条目（应唯一）: {upd['match']} -> "
                  f"{[(f.name, e.get('title')) for f, e in hits]}")
            sys.exit(1)
        f, e = hits[0]
        # 字段级更新
        for key, val in upd.get("fields", {}).items():
            e[key] = val
        # 正文修改：content 整篇替换 或 replace 逐句替换
        if "content" in upd:
            e["content"] = upd["content"]
        for old, new in upd.get("replace", []):
            if old not in e["content"]:
                print(f"  [警告] {upd['match']} 中找不到待替换句子（可能已修过）: {old[:40]}...")
            else:
                e["content"] = e["content"].replace(old, new)
        dirty.add(f)
        matched_updates += 1
        print(f"  ✓ {f.name} | {e['title']}")

    for f in dirty:
        lines = [json.dumps(e, ensure_ascii=False) for e in files[f]]
        f.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"语料：修改 {len(dirty)} 个文件、{matched_updates} 个条目")


def self_check():
    """一致性自检：A 类 severity/evidence 与规则库逐字一致 + advice 原文包含 + B 类枚举合法。"""
    rules = json.loads(RULES_PATH.read_text(encoding="utf-8"))
    by_id = {r["id"]: r for r in rules}
    valid_ev = {"guideline_label", "clinical_trial", "observational", "case_report", "theoretical", "mixed"}
    problems = 0
    for f in sorted(CORPUS_DIR.glob("*.jsonl")):
        for line in f.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            doc = json.loads(line)
            rid = doc.get("rule_id")
            if rid:
                rule = by_id.get(rid)
                if not rule:
                    print(f"  [错误] {doc['doc_id']} 的 rule_id={rid} 在规则库中不存在")
                    problems += 1
                    continue
                if doc["severity"] != rule["severity"] or doc["evidence_level"] != rule["evidence_level"]:
                    print(f"  [错误] {doc['doc_id']} {doc['title']} severity/evidence 与 {rid} 不一致")
                    problems += 1
                if rule["advice"] not in doc.get("content", ""):
                    print(f"  [错误] {doc['doc_id']} {doc['title']} 正文不包含 {rid} 的 advice 原文")
                    problems += 1
            ev = doc.get("evidence_level")
            if ev is not None and ev not in valid_ev:
                print(f"  [错误] {doc['doc_id']} {doc['title']} 使用非法 evidence_level: {ev}")
                problems += 1
    if problems:
        print(f"自检发现 {problems} 个问题")
        sys.exit(1)
    print("自检通过 ✓")


def main():
    # 1. 规则库
    print("== 1. 规则库修改 ==")
    rules = json.loads(RULES_PATH.read_text(encoding="utf-8"))
    apply_rule_fixes(rules)
    RULES_PATH.write_text(json.dumps(rules, ensure_ascii=False, indent=2), encoding="utf-8")

    # 2. 语料
    print("== 2. 语料条目修改 ==")
    apply_corpus_fixes()

    # 3. 一致性自检
    print("== 3. 一致性自检 ==")
    self_check()

    print("\n修复完成。下一步：python scripts/build_multihop_corpus.py --merge 重建合并产物并全量校验")


if __name__ == "__main__":
    main()
